#!/usr/bin/env node
// Builds src/data/venue-catalogue.js from scripts/venue-seeds.mjs by resolving each name against OpenStreetMap Nominatim.
// Polite by design: one request at a time, ≥1.1 s apart, identifying User-Agent, results cached locally in .data/ so an
// interrupted run resumes without repeating lookups. Run it rarely (data is a snapshot). Usage: node scripts/build-venue-catalogue.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { SEEDS } from './venue-seeds.mjs';
import { acceptResult } from '../src/venues/catalogueBuild.js';
import { BENGALURU_VIEWBOX } from '../src/geo/geocoder.js';
import { dedupeVenues } from '../src/venues/core.js';

const UA = 'MobiMeet-dev/0.1 (one-off venue snapshot build)';
const CACHE = '.data/venue-lookup-cache.json';
mkdirSync('.data', { recursive: true });
const cache = existsSync(CACHE) ? JSON.parse(readFileSync(CACHE, 'utf8')) : {};
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const today = new Date().toISOString().slice(0, 10);

let last = 0, fetched = 0;
async function lookup(q) {
  if (cache[q]) return cache[q];
  const wait = last + 1100 - Date.now(); if (wait > 0) await sleep(wait); last = Date.now();
  const url = `https://nominatim.openstreetmap.org/search?${new URLSearchParams({ q, format: 'jsonv2', limit: '5', viewbox: BENGALURU_VIEWBOX, bounded: '1', countrycodes: 'in' })}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } });
      if (res.status === 429 || res.status >= 500) { await sleep(5000 * (attempt + 1)); continue; }
      if (!res.ok) return (cache[q] = []);
      fetched++; return (cache[q] = await res.json());
    } catch { await sleep(3000); }
  }
  return null;   // network failure: not cached, reported as "not looked up"
}

const venues = [], unresolved = [], notLookedUp = [];
const seen = new Set();
let i = 0;
for (const seed of SEEDS) {
  i++;
  // Try "Name, Area, Bengaluru", then "Name, Bengaluru", then "Name Bangalore" — stopping at the first confirmed result. OSM often
  // has no entry for the area wording but does for the bare name.
  let hit = null, failed = false;
  const name = seed.q.split(',')[0].trim();
  for (const q of [seed.q, `${name}, Bengaluru`, `${name} Bangalore`]) {      // three phrasings; all use the SAME acceptance rules
    const results = await lookup(q);
    if (results === null) { failed = true; break; }
    hit = results.map(r => acceptResult(seed, r, today)).find(Boolean);
    if (hit) break;
  }
  if (failed && !hit) { notLookedUp.push(seed.q); continue; }
  if (!hit) { unresolved.push(`${seed.cat}: ${seed.q}`); }
  else if (!seen.has(hit.id)) { seen.add(hit.id); venues.push(hit); }
  if (i % 20 === 0) { writeFileSync(CACHE, JSON.stringify(cache)); console.log(`… ${i}/${SEEDS.length} seeds, ${venues.length} confirmed`); }
}
writeFileSync(CACHE, JSON.stringify(cache));
{ const before = venues.length; const unique = dedupeVenues(venues); venues.length = 0; venues.push(...unique); if (before !== venues.length) console.log(`removed ${before - venues.length} near-duplicate(s)`); }
venues.sort((a, b) => (a.category < b.category ? -1 : a.category > b.category ? 1 : a.name < b.name ? -1 : 1));

const header = `// ═══════════════════════════════════════════════════════════
//  data/venue-catalogue.js — GENERATED by scripts/build-venue-catalogue.mjs. Do not edit by hand.
//  A SNAPSHOT of well-known Bengaluru meetup places, each CONFIRMED against OpenStreetMap (place type, Bengaluru location and
//  name all matched; unconfirmed names were dropped). Coordinates and ids are OSM's. No ratings or opening hours are stored —
//  none were verified. © OpenStreetMap contributors (ODbL). Live lookups take precedence whenever they are reachable.
// ═══════════════════════════════════════════════════════════
`;
const meta = { generatedAt: today, source: 'OpenStreetMap via Nominatim', attribution: '© OpenStreetMap contributors (ODbL)', seedCount: SEEDS.length, confirmed: venues.length };
writeFileSync('src/data/venue-catalogue.js', `${header}export const VENUE_CATALOGUE = ${JSON.stringify({ ...meta, venues }, null, 0).replace(/\},\{/g, '},\n{')};\n`);
const byCat = Object.entries(venues.reduce((a, v) => ((a[v.category] = (a[v.category] ?? 0) + 1), a), {})).map(([c, n]) => `${c}: ${n}`).join(', ');
// (a build summary is printed below; no report file is written)
console.log(`\nDone: ${venues.length}/${SEEDS.length} confirmed (${fetched} live lookups). ${byCat}`);
